#pragma once
#include <cstddef>
#include <cstdint>

namespace dsr_mw2 {
// Layout shared with the original Win64 register-preserving entry shim.
struct EntryRegisters {
    unsigned char shadow[32], xmm[16][16];
    std::uint32_t mxcsr,padding;
    std::uint64_t r11,r10,r9,r8,rdx,rcx,rax,flags,return_address;
};
static_assert(offsetof(EntryRegisters,r11)==296);
static_assert(offsetof(EntryRegisters,rcx)==336);
static_assert(offsetof(EntryRegisters,flags)==352);
static_assert(offsetof(EntryRegisters,return_address)==360);
using EntryCallback=void(*)(const EntryRegisters&);
// Only these reviewed complete, non-relative prologues are supported. Never
// copies guessed instruction lengths or rewrites arbitrary machine code.
enum class EntryPoint : unsigned { frame, pad, item_delta, set_count, aim_camera, hud_reticle, player_visibility, render_present, count };
constexpr unsigned char frame_prefix[16]={0x48,0x8b,0xc4,0x57,0x48,0x83,0xec,0x70,
                                         0x48,0xc7,0x40,0xa8,0xfe,0xff,0xff,0xff};
constexpr unsigned char pad_prefix[21]={0x48,0x8b,0xc4,0x55,0x56,0x57,0x41,0x54,0x41,0x55,0x41,0x56,0x41,0x57,0x48,0x8d,0xa8,0x28,0xff,0xff,0xff};
constexpr unsigned char delta_prefix[16]={0x40,0x53,0x56,0x57,0x41,0x56,0x48,0x81,0xec,0x88,0x00,0x00,0x00,0x48,0x63,0xda};
constexpr unsigned char set_count_prefix[16]={0x48,0x89,0x5c,0x24,0x08,0x48,0x89,0x6c,0x24,0x10,0x48,0x89,0x74,0x24,0x18,0x57};
constexpr unsigned char aim_camera_prefix[16]={0x48,0x8b,0xc4,0x55,0x53,0x56,0x57,0x41,0x56,0x48,0x8d,0xa8,0x18,0xff,0xff,0xff};
constexpr unsigned char hud_reticle_prefix[18]={0x48,0x8b,0xc4,0x56,0x57,0x41,0x54,0x41,0x56,0x41,0x57,0x48,0x81,0xec,0x80,0,0,0};
constexpr unsigned char player_visibility_prefix[20]={0x48,0x89,0x5c,0x24,0x08,0x57,0x48,0x83,0xec,0x20,0x80,0xb9,0xa6,0x02,0,0,0x80,0x48,0x8b,0xd9};
constexpr unsigned char render_present_prefix[17]={0x48,0x89,0x5c,0x24,0x20,0x55,0x57,0x41,0x55,0x41,0x56,0x41,0x57,0x48,0x83,0xec,0x40};
bool install_entry_observer(void* target,EntryCallback callback,EntryPoint point=EntryPoint::frame);
// Typed redirects require separately verified target ABI. Trampoline is published
// before patch installation; caller owns its exact function-pointer type.
bool install_entry_redirect(void* target,void* redirect,EntryPoint point);
void* entry_trampoline(EntryPoint point);
bool remove_entry_observer(EntryPoint point=EntryPoint::frame);
}
